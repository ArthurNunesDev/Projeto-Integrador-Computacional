-- Notificações in-app (sino do cabeçalho). Mensagens não geram linha aqui: o contador delas vem de mensagens.lida.
-- V7 fica com a branch que remove contratacoes; esta precisa entrar depois dela.

CREATE TABLE notificacoes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario_id bigint       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    -- Quem causou a notificação (null quando não há uma pessoa por trás).
    ator_id         bigint       REFERENCES usuarios (id) ON DELETE CASCADE,
    tipo            varchar(40)  NOT NULL,
    -- Conexão ou oportunidade de origem. Sem FK: o alvo pode ser apagado e a notificação continua.
    alvo_id         bigint,
    -- Texto pronto em pt-BR, gravado na hora (não muda se o nome ou o título mudarem depois).
    texto           varchar(300) NOT NULL,
    -- Evita repetir a mesma notificação não lida, ex.: 'CONEXAO_SOLICITADA:12'.
    chave           varchar(100) NOT NULL,
    lida_em         timestamptz,
    criado_em       timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_notificacoes_tipo CHECK (tipo IN ('CONEXAO_SOLICITADA', 'CONEXAO_ACEITA', 'PARTICIPACAO_NOVA',
        'PARTICIPACAO_ACEITA', 'PARTICIPACAO_RECUSADA', 'OPORTUNIDADE_FECHADA', 'OPORTUNIDADE_REMOVIDA')),
    CONSTRAINT ck_notificacoes_distintos CHECK (ator_id IS NULL OR ator_id <> destinatario_id)
);

-- Lista do usuário, mais novas primeiro (cursor por id).
CREATE INDEX idx_notificacoes_destinatario_id ON notificacoes (destinatario_id, id DESC);
-- Contagem de não lidas.
CREATE INDEX idx_notificacoes_nao_lidas ON notificacoes (destinatario_id) WHERE lida_em IS NULL;
-- Uma não lida por chave: a repetição atualiza a existente (ON CONFLICT ... DO UPDATE).
CREATE UNIQUE INDEX uk_notificacoes_chave_nao_lida ON notificacoes (destinatario_id, chave) WHERE lida_em IS NULL;
-- ON DELETE CASCADE de ator_id.
CREATE INDEX idx_notificacoes_ator ON notificacoes (ator_id);
