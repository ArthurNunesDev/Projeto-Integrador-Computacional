-- Mensagens diretas: uma conversa por par de usuários.

CREATE TABLE conversas (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_a_id  bigint      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    usuario_b_id  bigint      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    criado_em     timestamptz NOT NULL DEFAULT now(),
    -- Muda a cada mensagem; ordena a lista de conversas.
    atualizado_em timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_conversas_distintos CHECK (usuario_a_id <> usuario_b_id)
);

-- Uma conversa só por par, em qualquer ordem (como em conexoes).
CREATE UNIQUE INDEX uk_conversas_par_sem_ordem
    ON conversas (LEAST(usuario_a_id, usuario_b_id), GREATEST(usuario_a_id, usuario_b_id));
CREATE INDEX idx_conversas_usuario_a ON conversas (usuario_a_id);
CREATE INDEX idx_conversas_usuario_b ON conversas (usuario_b_id);

CREATE TABLE mensagens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversa_id bigint        NOT NULL REFERENCES conversas (id) ON DELETE CASCADE,
    autor_id    bigint        NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    texto       varchar(2000) NOT NULL,
    -- Lida pelo outro participante (o autor não conta).
    lida        boolean       NOT NULL DEFAULT false,
    criado_em   timestamptz   NOT NULL DEFAULT now()
);

CREATE INDEX idx_mensagens_conversa_criado ON mensagens (conversa_id, criado_em);
CREATE INDEX idx_mensagens_autor ON mensagens (autor_id);
